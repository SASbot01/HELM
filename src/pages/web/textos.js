export function traductor(lang) {
  const d = TEXTOS[lang] || TEXTOS.es
  return (k) => (d[k] != null ? d[k] : (TEXTOS.es[k] != null ? TEXTOS.es[k] : k))
}

export function idiomaInicial() {
  try {
    const q = new URLSearchParams(window.location.search).get('lang')
    if (IDIOMAS.includes(q)) return q
    const s = localStorage.getItem('helm-web-lang')
    if (IDIOMAS.includes(s)) return s
  } catch { /* sin almacenamiento: se decide por el navegador */ }
  const nav = navigator.languages?.length ? navigator.languages : [navigator.language || 'es']
  for (const l of nav) {
    const c = String(l || '').slice(0, 2).toLowerCase()
    if (IDIOMAS.includes(c)) return c
  }
  return 'es'
}
